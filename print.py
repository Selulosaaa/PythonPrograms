# print adlah cara kita untuk memunculkan sebuah teks pada terminal

# untuk memunculkan sebuah string(huruf) harus menggunakan tanda petik
print("hello world") # output --> hello world

# untuk print sebuah interger atau sebuah angka di python tidak mennggunakan tanda petik
print(30) #output --> 30

# print dapat dikombinasikan langsung dengan "*" untuk menghasilkan teks yang sama berturut
print("halo" * 30) # namun ini hanya satu baris saja

# print dengan variabel dapat bervariasi, contoh
a = "ini adalah isi dari variabel:"
b = "ini isinya"
print(a) # --> tanpa menggunakan tanda petik
# jika ingin menggunakan 2 atau lebih variabel atau dikombinasikan dengan string
# bisa pakai "+" untuk tanpa spasi dan (,) untuk spasi
print(a + b) #tanpa spasi
print(a, b) # pakai spasi