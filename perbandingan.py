# operator perbandingan digunakan untuk membandingkan dua data/kondisi
# hasil akhir dari operator ini antara false atau true

# kita ingin membandingkan 2 nilai berikut
a = 40
b = 30

print(a == b) # a sama dengan b, output False karena a dan b bukanlah nilai yang sama
print(a != b) # a TIDAK sama dengan b, ouput True karena a dan b nilai yang berbeda
print(a > b) # a lebih besar dari b, output True karena a nilai nya lebih besar dari b
print(a < b) # a lebih kecil dari b, output False karena b nilainya lebih kecil dari a
print(a >= b) # a lebih besar atau sama dengan b, output True
print(a <= b) # a lebih kecil atau sama dengan b, output False