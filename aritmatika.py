# Operator aritmatika adalah sebuah operator untuk operasi matematika
# memakai beberapa simbol matematika untuk sebuah perhitungan.

# kita akan memakai variabel yang sudah kita isi angka
a = 20
b = 10

# pertambahan "+"
print(a + b) # 30

# pengurangan "-"
print(a - b) # 10
print(b - a) # -10

# perkalian "*"
print(a * b) # 200

# pembagian "/"
print(a / b)

# urutan pengerjaan juga sudah sesuai dengan aturan yang berlaku di matematika
print(30 + 20 * 9 / 10) # pengerjaan perkalian terlebih dahulu
print((30 + 20) * 9 / 10) # tanda kuruung bisa dipakai untuk operasi mana yang dikerjakan terlebih dahulu
